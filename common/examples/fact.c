// ============================================================================
// 阶乘 —— 指导书 1.3 节"基础样例程序"的第一个示例
//
// 原示例用的是 C++ 的 cin / cout，这里改写成 SysY 的 getint / putint
// （SysY 是 C 的子集，没有 iostream）。除此之外与指导书完全一致。
//
// 这个程序的用途：
//   A：看四个阶段的产物，尤其 while 循环在 LLVM IR 里对应哪几个基本块
//   B：看 while 循环在 RISC-V 汇编里对应哪些指令和跳转标签
//
// 输入输出只有一行：读入 n，输出 n! 的值（不换行，与指导书一致）
// ============================================================================
int getint(void);
void putint(int x);
void putch(int x);

int main()
{
    int i;
    int n;
    int f;

    n = getint();
    i = 2;
    f = 1;
    while (i <= n) {
        f = f * i;
        i = i + 1;
    }
    putint(f);
    putch(10);      /* '\n'，对应原示例的 endl */
    return 0;
}
