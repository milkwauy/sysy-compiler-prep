// ============================================================================
// 斐波那契数列 —— 指导书 1.3 节"基础样例程序"的第二个示例
//
// 原示例用的是 C++ 的 cin / cout，这里改写成 SysY 的 getint / putint。
// 注意原示例里 t 这个临时变量是"故意"写的（b 先存到 t，再把 t 赋给 a），
// 这正是好看的观察点：编译器/后端会不会真的为它分配资源？
//   A：-O0 的 IR 里能看到 load/store 往返，-O2 之后会不会被优化掉？
//   B：汇编里编译器是直接用寄存器倒腾，还是真的落到栈上？
//
// 输入 n，输出 a、b，然后循环输出接下来的每一项，每行一个。
// ============================================================================
int getint(void);
void putint(int x);
void putch(int x);

int main()
{
    int a;
    int b;
    int i;
    int t;
    int n;

    a = 0;
    b = 1;
    i = 1;
    n = getint();
    putint(a);
    putch(10);
    putint(b);
    putch(10);
    while (i < n) {
        t = b;
        b = a + b;
        putint(b);
        putch(10);
        a = t;
        i = i + 1;
    }
    return 0;
}
